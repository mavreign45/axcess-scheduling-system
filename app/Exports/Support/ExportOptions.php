<?php

namespace App\Exports\Support;

use App\Models\User;
use App\Services\PeriodResolver;
use Carbon\Carbon;
use Illuminate\Support\Str;

final class ExportOptions
{
    public function __construct(
        public Carbon $start,
        public Carbon $end,
        public ?int $departmentId = null,
        public ?int $userId = null,
        public ?int $shiftTypeId = null,
        public ?string $assignmentStatus = null,
        public bool $standbyOnly = false,
        public ?string $employmentStatus = null,
        public ?string $leaveType = null,
        public ?string $leaveStatus = null,
        public bool $includeSensitive = false,
        public bool $includeContacts = false,
        public bool $includeAbsences = true,
        public array $worksheets = ['schedule'],
        public string $reportType = 'full',
        public string $format = 'xlsx',
        public ?User $generatedBy = null,
        public array $filterLabels = [],
    ) {}

    public function periodLabel(): string
    {
        return PeriodResolver::label($this->start, $this->end);
    }

    public function generatedLabel(): string
    {
        $timezone = config('axcess.exports.timezone_label', 'UTC');
        $generated = now()->setTimezone(config('app.timezone'))->format('M j, Y g:i A');
        $author = $this->generatedBy
            ? $this->generatedBy->full_name.' ('.$this->generatedBy->roleLabel().')'
            : 'System';

        return "Generated: {$generated} ({$timezone}) · Generated by: {$author}";
    }

    public function filtersLabel(): string
    {
        if ($this->filterLabels === []) {
            return 'All available records';
        }

        return implode(' · ', array_values(array_filter($this->filterLabels)));
    }

    public function hasWorksheet(string $key): bool
    {
        return in_array($key, $this->worksheets, true);
    }

    public function filename(string $type): string
    {
        $type = Str::studly($type);
        $start = $this->start->format('Y-m-d');
        $end = $this->end->format('Y-m-d');
        $period = $start === $end ? $start : "{$start}_to_{$end}";

        return "Axcess_{$type}_{$period}.{$this->format}";
    }

    public function logSummary(): array
    {
        return [
            'period_start' => $this->start->toDateString(),
            'period_end' => $this->end->toDateString(),
            'department_id' => $this->departmentId,
            'user_id' => $this->userId,
            'shift_type_id' => $this->shiftTypeId,
            'assignment_status' => $this->assignmentStatus,
            'standby_only' => $this->standbyOnly,
            'employment_status' => $this->employmentStatus,
            'leave_type' => $this->leaveType,
            'leave_status' => $this->leaveStatus,
            'worksheet' => $this->worksheets,
            'report_type' => $this->reportType,
            'format' => $this->format,
        ];
    }
}
